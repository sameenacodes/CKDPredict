@app.route(
    "/patient-risk-trend/<path:patient_name>"
)
def patient_risk_trend(patient_name):

    conn = get_db_connection()

    assessments = conn.execute(
        """
        SELECT
            id,
            patient_name,
            age,
            prediction,
            risk,
            confidence,
            ckd_probability,
            created_at
        FROM patient_history
        WHERE patient_name = ?
        ORDER BY created_at ASC, id ASC
        """,
        (patient_name,)
    ).fetchall()

    conn.close()

    if not assessments:
        return (
            "No assessment history found for this patient.",
            404
        )

    trend_data = []

    for assessment in assessments:

        probability = assessment["ckd_probability"]

        # Backward compatibility for old records.
        if probability is None:

            if (
                assessment["prediction"]
                == "Chronic Kidney Disease Detected"
            ):

                probability = float(
                    assessment["confidence"] or 0
                )

            elif (
                assessment["prediction"]
                == "No Chronic Kidney Disease Detected"
            ):

                probability = round(
                    100 - float(
                        assessment["confidence"] or 0
                    ),
                    2
                )

            else:
                probability = 0

        trend_data.append({

            "id": assessment["id"],

            "date": assessment["created_at"],

            "prediction": assessment["prediction"],

            "risk": assessment["risk"],

            "ckd_probability": round(
                float(probability or 0),
                2
            )

        })

    latest = trend_data[-1]

    previous = (
        trend_data[-2]
        if len(trend_data) > 1
        else None
    )

    trend_direction = "Stable"
    trend_change = 0

    if previous:

        trend_change = round(
            latest["ckd_probability"]
            - previous["ckd_probability"],
            2
        )

        if trend_change > 2:
            trend_direction = "Increasing"

        elif trend_change < -2:
            trend_direction = "Decreasing"

    probability = latest["ckd_probability"]

    if probability >= 70:
        trend_risk = "High"

    elif probability >= 40:
        trend_risk = "Moderate"

    else:
        trend_risk = "Low"

    return render_template(
        "patient_risk_trend.html",
        patient_name=patient_name,
        assessments=trend_data,
        latest=latest,
        previous=previous,
        trend_direction=trend_direction,
        trend_change=trend_change,
        trend_risk=trend_risk
    )


