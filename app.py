# DECODE CKD LABEL
# ============================================================

def decode_ckd_label(value):

    """
    Converts a model/CSV label into:

        0 = CKD
        1 = No CKD

    Returns None when the value is unknown.

    Supported labels include:

        CKD
        No CKD
        ckd
        notckd
        positive
        negative
        yes
        no
        0
        1
    """

    value = normalize_value(
        value
    )


    # ========================================================
    # NUMERIC
    # ========================================================

    if isinstance(
        value,
        (int, float)
    ):

        try:

            number = float(value)


            if number == 0:

                return 0


            if number == 1:

                return 1


        except Exception:

            pass


    # ========================================================
    # STRING NUMERIC
    # ========================================================

    if isinstance(
        value,
        str
    ):

        if value in [
            "0",
            "0.0"
        ]:

            return 0


        if value in [
            "1",
            "1.0"
        ]:

            return 1


    # ========================================================
    # CKD LABELS
    # ========================================================

    if isinstance(
        value,
        str
    ):

        if value in [

            "ckd",

            "chronic kidney disease",

            "chronic kidney disease detected",

            "disease",

            "positive",

            "yes",

            "ckd detected",

            "ckd_positive",

            "ckd-positive"

        ]:

            return 0


    # ========================================================
    # NO CKD LABELS
    # ========================================================

    if isinstance(
        value,
        str
    ):

        if value in [

            "notckd",

            "not ckd",

            "no ckd",

            "no chronic kidney disease",

            "no chronic kidney disease detected",

            "healthy",

            "negative",

            "no",

            "normal",

            "not disease",

            "non-ckd",

            "non ckd",

            "no_ckd",

            "not_ckd"

        ]:

            return 1


    return None


