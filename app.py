def decode_model_prediction(raw_prediction):

    """
    Converts the model's raw prediction into:

        0 = CKD
        1 = No CKD

    The saved model may use different raw class labels.

    Supported examples:

        0 / 1       -> 0 = CKD, 1 = No CKD

        1 / 2       -> 1 = No CKD, 2 = CKD

        'ckd'       -> CKD

        'notckd'    -> No CKD
    """

    # ========================================================
    # NORMALIZE
    # ========================================================

    normalized_prediction = normalize_value(
        raw_prediction
    )


    # ========================================================
    # STRING LABELS
    # ========================================================

    if isinstance(
        normalized_prediction,
        str
    ):

        # ----------------------------------------------------
        # CKD
        # ----------------------------------------------------

        if normalized_prediction in [

            "ckd",
            "chronic kidney disease",
            "chronic kidney disease detected",
            "ckd detected",
            "disease",
            "positive",
            "yes",
            "ckd_positive",
            "ckd-positive"

        ]:

            return 0


        # ----------------------------------------------------
        # NO CKD
        # ----------------------------------------------------

        if normalized_prediction in [

            "notckd",
            "not ckd",
            "no ckd",
            "no chronic kidney disease",
            "no chronic kidney disease detected",
            "healthy",
            "negative",
            "no",
            "normal",
            "not disease",
            "non-ckd",
            "non ckd",
            "no_ckd",
            "not_ckd"

        ]:

            return 1


    # ========================================================
    # MODEL CLASSES
    # ========================================================

    classes = None


    if hasattr(
        model,
        "classes_"
    ):

        try:

            classes = list(
                model.classes_
            )

        except Exception:

            classes = None


    # ========================================================
    # DEBUG INFORMATION
    # ========================================================

    if classes is not None:

        print(
            "MODEL CLASS MAPPING"
        )

        print(
            "Raw prediction:",
            repr(raw_prediction)
        )

        print(
            "Model classes:",
            classes
        )


    # ========================================================
    # CURRENT MODEL:
    #
    # 1 = NO CKD
    # 2 = CKD
    # ========================================================

    if classes is not None:

        try:

            numeric_classes = [

                float(
                    normalize_value(
                        class_value
                    )
                )

                for class_value in classes

            ]


            if set(
                numeric_classes
            ) == {1.0, 2.0}:

                numeric_prediction = float(
                    normalized_prediction
                )


                if numeric_prediction == 2:

                    return 0


                if numeric_prediction == 1:

                    return 1


        except Exception:

            pass


    # ========================================================
    # STANDARD MODEL:
    #
    # 0 = CKD
    # 1 = NO CKD
    # ========================================================

    if classes is not None:

        try:

            numeric_classes = [

                float(
                    normalize_value(
                        class_value
                    )
                )

                for class_value in classes

            ]


            if set(
                numeric_classes
            ) == {0.0, 1.0}:

                numeric_prediction = float(
                    normalized_prediction
                )


                if numeric_prediction == 0:

                    return 0


                if numeric_prediction == 1:

                    return 1


        except Exception:

            pass


    # ========================================================
    # NUMERIC FALLBACK
    # ========================================================

    try:

        numeric_prediction = float(
            normalized_prediction
        )


        # ----------------------------------------------------
        # Current saved model
        #
        # 2 = CKD
        # ----------------------------------------------------

        if numeric_prediction == 2:

            return 0


        # ----------------------------------------------------
        # Existing application convention
        #
        # 0 = CKD
        # 1 = No CKD
        # ----------------------------------------------------

        if numeric_prediction == 0:

            return 0


        if numeric_prediction == 1:

            return 1


    except Exception:

        pass


    # ========================================================
    # UNKNOWN
    # ========================================================

    return None


