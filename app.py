def prepare_validation_data(df):

    """
    Converts CSV data into exactly the same
    8 model features used during prediction.
    """

    data = df[
        MODEL_FEATURES
    ].copy()


    # ========================================================
    # NUMERIC FEATURES
    # ========================================================

    numerical_features = [

        "sg",
        "al",
        "hemo",
        "rc"

    ]


    for column in numerical_features:

        data[column] = pd.to_numeric(

            data[column],

            errors="coerce"

        )


    # ========================================================
    # TEXT CLEANER
    # ========================================================

    def clean_text(value):

        if pd.isna(value):

            return ""

        return str(
            value
        ).strip().lower()


    # ========================================================
    # HYPERTENSION
    # ========================================================

    data["htn"] = (

        data["htn"]

        .apply(clean_text)

        .map({

            "yes": 1,

            "no": 0,

            "1": 1,

            "0": 0,

            "true": 1,

            "false": 0

        })

    )


    # ========================================================
    # DIABETES
    # ========================================================

    data["dm"] = (

        data["dm"]

        .apply(clean_text)

        .map({

            "yes": 1,

            "no": 0,

            "1": 1,

            "0": 0,

            "true": 1,

            "false": 0

        })

    )


    # ========================================================
    # APPETITE
    # ========================================================

    data["appet"] = (

        data["appet"]

        .apply(clean_text)

        .map({

            "poor": 1,

            "good": 0,

            "1": 1,

            "0": 0

        })

    )


    # ========================================================
    # PUS CELL
    # ========================================================

    data["pc"] = (

        data["pc"]

        .apply(clean_text)

        .map({

            "normal": 1,

            "abnormal": 0,

            "1": 1,

            "0": 0

        })

    )


    # ========================================================
    # FORCE NUMERIC DATA TYPES
    #
    # Prevents XGBoost dtype errors.
    # ========================================================

    for column in MODEL_FEATURES:

        data[column] = pd.to_numeric(

            data[column],

            errors="coerce"

        )


    return data


