def create_database():

    conn = get_db_connection()

    conn.execute("""
        CREATE TABLE IF NOT EXISTS patient_history (

            id INTEGER PRIMARY KEY AUTOINCREMENT,

            patient_name TEXT NOT NULL,

            age REAL,

            sg REAL,

            al REAL,

            hemo REAL,

            rc REAL,

            htn TEXT,

            dm TEXT,

            appet TEXT,

            pc TEXT,

            prediction TEXT,

            risk TEXT,

            confidence REAL,

            ckd_probability REAL,

            gender TEXT,

            serum_creatinine REAL,

            egfr REAL,

            gfr_stage TEXT,

            created_at TEXT

        )
    """)

    conn.commit()

    # Migrate an existing patient_history.db safely.
    columns = conn.execute(
        "PRAGMA table_info(patient_history)"
    ).fetchall()

    column_names = [column["name"] for column in columns]

    if "ckd_probability" not in column_names:
        conn.execute("""
            ALTER TABLE patient_history
            ADD COLUMN ckd_probability REAL
        """)
        conn.commit()
        print("Database updated: ckd_probability column added.")

    # Module 5 migration: eGFR-related fields.
    migrations = {
        "gender": "TEXT",
        "serum_creatinine": "REAL",
        "egfr": "REAL",
        "gfr_stage": "TEXT",
        "bp": "REAL",
    }

    for column, column_type in migrations.items():
        if column not in column_names:
            conn.execute(
                f"ALTER TABLE patient_history ADD COLUMN {column} {column_type}"
            )
            conn.commit()
            print(f"Database updated: {column} column added.")

    conn.close()


