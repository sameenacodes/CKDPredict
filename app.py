def normalize_value(value):

    """
    Converts numpy/scikit-learn values into
    simple Python values.
    """

    try:

        if hasattr(
            value,
            "item"
        ):

            value = value.item()

    except Exception:

        pass


    if isinstance(
        value,
        bytes
    ):

        try:

            value = value.decode(
                "utf-8"
            )

        except Exception:

            value = str(value)


    if isinstance(
        value,
        str
    ):

        value = value.strip().lower()


        # Handle strings such as b'ckd'

        if (
            value.startswith("b'")
            and
            value.endswith("'")
        ):

            value = value[2:-1].strip().lower()


        elif (
            value.startswith('b"')
            and
            value.endswith('"')
        ):

            value = value[2:-1].strip().lower()


    return value


