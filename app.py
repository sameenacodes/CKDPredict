def _report_text(value, default="N/A"):
    """Convert database values safely to displayable report text."""
    if value is None or str(value).strip() == "":
        return default
    return str(value)


def _report_para(text, style):
    """Create a ReportLab paragraph with safe HTML escaping."""
    return Paragraph(html.escape(_report_text(text)).replace("\n", "<br/>"), style)


def build_assessment_pdf(patient, lang='en'):
    lang = report_lang(lang)
    labels = REPORT_LABELS[lang]
    """Build a professional PDF report from a saved patient_history row."""
    patient = dict(patient)

    # Recreate the recommendation/XAI information from the saved assessment.
    prediction_text = _report_text(patient.get("prediction"))
    risk = _report_text(patient.get("risk"))
    confidence = patient.get("confidence")
    ckd_probability = patient.get("ckd_probability")
    age = patient.get("age")
    gender = _report_text(patient.get("gender"))
    serum_creatinine = patient.get("serum_creatinine")
    egfr = patient.get("egfr")
    gfr_stage = _report_text(patient.get("gfr_stage"), "Not Available")

    # Rebuild recommendations using exactly the same decision-support engine.
    try:
        recommendations, warnings = get_recommendations(
            prediction_value=0 if prediction_text == "Chronic Kidney Disease Detected" else 1,
            ckd_probability=float(ckd_probability or 0),
            sg=float(patient.get("sg") or 0),
            al=float(patient.get("al") or 0),
            hemo=float(patient.get("hemo") or 0),
            rc=float(patient.get("rc") or 0),
            htn_value=_report_text(patient.get("htn"), ""),
            dm_value=_report_text(patient.get("dm"), ""),
            appet_value=_report_text(patient.get("appet"), ""),
            pc_value=_report_text(patient.get("pc"), "")
        )
    except Exception:
        recommendations, warnings = [], []

    # Rebuild XAI factor explanation when the model is available.
    explanations = []
    try:
        input_data = pd.DataFrame([[
            float(patient.get("sg") or 0),
            float(patient.get("al") or 0),
            float(patient.get("hemo") or 0),
            float(patient.get("rc") or 0),
            1 if str(patient.get("htn", "")).lower() == "yes" else 0,
            1 if str(patient.get("dm", "")).lower() == "yes" else 0,
            1 if str(patient.get("appet", "")).lower() == "poor" else 0,
            1 if str(patient.get("pc", "")).lower() == "normal" else 0,
        ]], columns=MODEL_FEATURES)
        prediction_value = 0 if prediction_text == "Chronic Kidney Disease Detected" else 1
        explanations = get_prediction_explanation(input_data, prediction_value)
    except Exception:
        explanations = []

    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    report_font = "NotoTamil" if lang == "ta" and TAMIL_FONT_AVAILABLE else "Helvetica"
    title = ParagraphStyle(
        "CKDReportTitle", parent=styles["Title"], alignment=TA_CENTER,
        fontName=report_font, fontSize=21, leading=25, spaceAfter=5
    )
    subtitle = ParagraphStyle(
        "CKDReportSubtitle", parent=styles["Normal"], alignment=TA_CENTER,
        fontName=report_font, fontSize=9.5, leading=13, spaceAfter=16
    )
    section = ParagraphStyle(
        "CKDReportSection", parent=styles["Heading2"],
        fontName=report_font, fontSize=13, leading=17, spaceBefore=12, spaceAfter=7
    )
    body = ParagraphStyle(
        "CKDReportBody", parent=styles["BodyText"],
        fontName=report_font, fontSize=9.2, leading=13
    )
    small = ParagraphStyle(
        "CKDReportSmall", parent=styles["BodyText"],
        fontName=report_font, fontSize=8, leading=11
    )

    story = [
        Paragraph("CKDPredict", title),
        Paragraph(labels["subtitle"], subtitle),
    ]

    # 1. Assessment summary
    story.append(Paragraph(labels["summary"], section))
    summary = [
         [labels["assessment_id"], _report_text(patient.get("id"))],
         [labels["date"], _report_text(patient.get("created_at"))],
         [labels["patient"], _report_text(patient.get("patient_name"))],
         [labels["age"], _report_text(age)],
         [labels["gender"], gender],
         [labels["prediction"], rtext(prediction_text, lang)],
         [labels["risk"], rtext(risk, lang)],
         [labels["confidence"], f"{float(confidence):.2f}%" if confidence is not None else "N/A"],
         [labels["probability"], f"{float(ckd_probability):.2f}%" if ckd_probability is not None else "N/A"],
    ]
    table = Table(summary, colWidths=[1.85*inch, 4.55*inch])
    table.setStyle(TableStyle([
        ("GRID", (0,0), (-1,-1), 0.4, colors.grey),
        ("BACKGROUND", (0,0), (0,-1), colors.whitesmoke),
        ("FONTNAME", (0,0), (0,-1), report_font),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("PADDING", (0,0), (-1,-1), 6),
        ("FONTSIZE", (0,0), (-1,-1), 8.5),
    ]))
    story += [table, Spacer(1, 8)]

    # 2. Kidney function
    story.append(Paragraph(labels["kidney"], section))
    kidney_rows = [
         [labels["creatinine"], _report_text(serum_creatinine) + " mg/dL"],
         [labels["egfr"], _report_text(egfr) + " mL/min/1.73 m²"],
         [labels["category"], gfr_stage],
         [labels["description"], get_gfr_description(gfr_stage)],
    ]
    kt = Table(kidney_rows, colWidths=[1.85*inch, 4.55*inch])
    kt.setStyle(TableStyle([
        ("GRID", (0,0), (-1,-1), 0.4, colors.grey),
        ("BACKGROUND", (0,0), (0,-1), colors.whitesmoke),
        ("FONTNAME", (0,0), (0,-1), report_font),
        ("PADDING", (0,0), (-1,-1), 6),
        ("FONTSIZE", (0,0), (-1,-1), 8.5),
    ]))
    story += [kt, Spacer(1, 4)]
    story.append(_report_para(
        labels["egfr_note"],
        small
    ))

    # 3. Key clinical parameters
    story.append(Paragraph(labels["clinical"], section))
    clinical = [
        ["Parameter", "Recorded Value"],
        ["Specific Gravity", _report_text(patient.get("sg"))],
        ["Albumin", _report_text(patient.get("al"))],
        ["Hemoglobin", _report_text(patient.get("hemo"))],
        ["RBC Count", _report_text(patient.get("rc"))],
        ["Blood Pressure", _report_text(patient.get("bp"), "Not stored")],
    ]
    ct = Table(clinical, colWidths=[2.6*inch, 3.8*inch], repeatRows=1)
    ct.setStyle(TableStyle([
        ("GRID", (0,0), (-1,-1), 0.4, colors.grey),
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#1d4ed8")),
        ("TEXTCOLOR", (0,0), (-1,0), colors.white),
        ("FONTNAME", (0,0), (-1,0), report_font),
        ("PADDING", (0,0), (-1,-1), 6),
        ("FONTSIZE", (0,0), (-1,-1), 8.5),
    ]))
    story.append(ct)

    # 4. Medical history
    story.append(Paragraph(labels["history"], section))
    history = [
        ["Factor", "Value"],
        ["Hypertension", _report_text(patient.get("htn"))],
        ["Diabetes Mellitus", _report_text(patient.get("dm"))],
        ["Appetite", _report_text(patient.get("appet"))],
        ["Pus Cell", _report_text(patient.get("pc"))],
    ]
    ht = Table(history, colWidths=[2.6*inch, 3.8*inch], repeatRows=1)
    ht.setStyle(TableStyle([
        ("GRID", (0,0), (-1,-1), 0.4, colors.grey),
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#1d4ed8")),
        ("TEXTCOLOR", (0,0), (-1,0), colors.white),
        ("FONTNAME", (0,0), (-1,0), report_font),
        ("PADDING", (0,0), (-1,-1), 6),
        ("FONTSIZE", (0,0), (-1,-1), 8.5),
    ]))
    story.append(ht)

    # 5. XAI
    # The explanation engine returns:
    #   name, value, importance, message
    # Older PDF code expected different keys (feature, impact, reason),
    # which caused blank XAI details in the generated PDF.
    story.append(Paragraph(labels["xai"], section))
    if explanations:
        for item in explanations[:6]:
            if isinstance(item, dict):
                feature = item.get("name", item.get("feature", "Feature"))
                value = item.get("value", "N/A")
                importance = item.get("importance", item.get("impact", "N/A"))
                reason = item.get(
                    "message",
                    item.get("reason", "Model factor considered in the prediction.")
                )
            else:
                feature = "Feature"
                value = "N/A"
                importance = "N/A"
                reason = "Model factor considered in the prediction."

            xai_text = (
                f"{feature}: value={value}; "
                f"model importance={importance}%. {reason}"
            )

            story.append(_report_para(xai_text, body))
            story.append(Spacer(1, 3))
    else:
        story.append(
            _report_para(
                "Feature explanation was not available for this saved assessment.",
                body
            )
        )

    # 6. Warnings + recommendations
    story.append(Paragraph(labels["support"], section))
    if warnings:
        story.append(Paragraph(labels["warnings"], styles["Heading3"]))
        for warning in warnings:
            # The recommendation engine currently returns warning messages
            # as strings. Older versions may return dictionaries, so support
            # both formats to keep PDF generation backward-compatible.
            if isinstance(warning, dict):
                warning_text = (
                    f"{warning.get('param', 'Parameter')}: "
                    f"{warning.get('value', 'N/A')} — "
                    f"{warning.get('message', '')}"
                )
            else:
                warning_text = str(warning)

            story.append(_report_para("• " + warning_text, body))
            story.append(Spacer(1, 3))
    if recommendations:
        story.append(Paragraph(labels["recommendations"], styles["Heading3"]))
        for recommendation in recommendations:
            if isinstance(recommendation, dict):
                title = recommendation.get("title", "Recommendation")
                message = recommendation.get("message", "")
                priority = recommendation.get("priority", "")
                recommendation_text = f"{title}"
                if priority:
                    recommendation_text += f" [{priority}]"
                if message:
                    recommendation_text += f": {message}"
            else:
                recommendation_text = str(recommendation)

            story.append(_report_para("• " + recommendation_text, body))
            story.append(Spacer(1, 3))
    if not warnings and not recommendations:
        story.append(_report_para("No additional decision-support items were generated.", body))

    story.append(Spacer(1, 12))
    story.append(Paragraph(labels["notice"], section))
    story.append(_report_para(
        labels["not_diagnosis"],
        small
    ))

    doc.build(story)
    buffer.seek(0)
    return buffer


@app.route("/download-report/<int:assessment_id>")
def download_report(assessment_id):
    """Generate and download a PDF report for a saved assessment."""
    conn = get_db_connection()
    patient = conn.execute(
        "SELECT * FROM patient_history WHERE id = ?",
        (assessment_id,)
    ).fetchone()
    conn.close()

    if patient is None:
        return "Assessment not found.", 404

    lang = report_lang(request.args.get("lang", "en"))
    pdf_buffer = build_assessment_pdf(patient, lang=lang)
    safe_name = "".join(
        ch for ch in str(patient["patient_name"] or "Patient")
        if ch.isalnum() or ch in "-_"
    ) or "Patient"
    suffix = "_Tamil" if lang == "ta" else "_English"
    filename = f"CKDPredict_Report_{safe_name}_{assessment_id}{suffix}.pdf"

    return send_file(
        pdf_buffer,
        as_attachment=True,
        download_name=filename,
        mimetype="application/pdf"
    )


