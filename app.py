def calculate_egfr(age, gender, creatinine):
    """
    Calculate estimated GFR using the MDRD equation used by this project.

    eGFR = 175 * (Scr ** -1.154) * (Age ** -0.203)
    Female adjustment = 0.742

    Returns eGFR in mL/min/1.73 m², rounded to one decimal place.
    """
    try:
        age = float(age)
        creatinine = float(creatinine)
    except (TypeError, ValueError):
        return None

    if age <= 0 or creatinine <= 0:
        return None

    egfr = 175 * (creatinine ** -1.154) * (age ** -0.203)

    if str(gender).strip().lower() == "female":
        egfr *= 0.742

    return round(float(egfr), 1)


def get_gfr_stage(egfr):
    """Return the KDIGO-style GFR category for a calculated eGFR."""
    if egfr is None:
        return "Not Available"

    egfr = float(egfr)

    if egfr >= 90:
        return "G1"
    elif egfr >= 60:
        return "G2"
    elif egfr >= 45:
        return "G3a"
    elif egfr >= 30:
        return "G3b"
    elif egfr >= 15:
        return "G4"
    else:
        return "G5"


