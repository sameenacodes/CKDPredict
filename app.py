# CKD PROBABILITY
# ============================================================

def get_ckd_probability(input_data, prediction_value):

    """
    Returns CKD probability specifically.

    Internal representation:
        0 = CKD
        1 = No CKD
    """

    if model is None or not hasattr(model, "predict_proba"):
        return None

    try:

        probabilities = model.predict_proba(input_data)[0]

        if hasattr(model, "classes_"):

            classes = list(model.classes_)

            if len(classes) == len(probabilities):

                for index, class_value in enumerate(classes):

                    decoded_class = decode_model_prediction(
                        class_value
                    )

                    if decoded_class == 0:

                        return round(
                            float(probabilities[index]) * 100,
                            2
                        )

        # Fallback if class metadata is unavailable.
        if prediction_value == 0:

            return round(
                float(max(probabilities)) * 100,
                2
            )

        if len(probabilities) >= 2:

            return round(
                float(min(probabilities)) * 100,
                2
            )

    except Exception as e:

        print("CKD PROBABILITY ERROR:", e)

    return None


